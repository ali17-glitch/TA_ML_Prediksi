def run_academic_pipeline():
    """
    Menjalankan seluruh pipeline data akademis secara lengkap untuk penilaian dosen:
    Pembersihan data, Feature Engineering, Training 3 Model, Evaluasi Metrik, dan Ekspor Grafik.
    """
    print("=" * 80)
    print("   BAGIAN A: PROSES PEMODELAN AKADEMIS - SMART CITY POVERTY PREDICTION")
    print("=" * 80)
    
    import pandas as pd
    import numpy as np
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import seaborn as sns
    from sklearn.preprocessing import StandardScaler
    from sklearn.model_selection import train_test_split
    from sklearn.linear_model import LinearRegression
    from sklearn.ensemble import RandomForestRegressor
    from sklearn.ensemble import GradientBoostingRegressor
    from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
    
    dataset_path = r"C:\Users\user\Downloads\Data_Tingkat_Kemiskinan.xlsx"
    if not os.path.exists(dataset_path):
        dataset_path = "Data_Tingkat_Kemiskinan.xlsx"
        
    print(f"[INFO] Membaca dataset dari {dataset_path}...")
    df = pd.read_excel(dataset_path)
    
    # 1. Preprocessing & Feature Engineering
    print("[INFO] Melakukan Preprocessing & Feature Engineering...")
    df['PengeluaranPerkapita_Rokok'] = df['PengeluaranPerkapita_Rokok'].fillna(df['PengeluaranPerkapita_Rokok'].median())
    
    # Rasio-rasio fitur baru
    df['Rasio_Ekonomi'] = df['PDRB'] / (df['PengeluaranPerKapita'] + 1e-5)
    df['Rasio_Pendidikan'] = df['HLS'] / (df['RLS'] + 1e-5)
    df['Rasio_Rokok'] = df['PengeluaranPerkapita_Rokok'] / (df['PengeluaranPerKapita'] + 1e-5)
    
    # Split Fitur & Target
    X = df[['RLS', 'IPG', 'UHH', 'PengeluaranPerKapita', 'HLS', 'PDRB', 'IKK', 'PengeluaranPerkapita_Rokok', 'Rasio_Ekonomi', 'Rasio_Pendidikan', 'Rasio_Rokok']]
    y = df['Tingkat_Penduduk_Miskin']
    
    # Scaling
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)
    
    X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)
    
    # 2. Training Models
    print("[INFO] Melatih model Machine Learning...")
    model_lr = LinearRegression()
    model_lr.fit(X_train, y_train)
    
    model_rf = RandomForestRegressor(n_estimators=100, random_state=42)
    model_rf.fit(X_train, y_train)
    
    model_gb = GradientBoostingRegressor(random_state=42)
    model_gb.fit(X_train, y_train)
    
    # 3. Evaluasi Model
    y_pred_lr = model_lr.predict(X_test)
    y_pred_rf = model_rf.predict(X_test)
    y_pred_gb = model_gb.predict(X_test)
    
    print("\n" + "=" * 40)
    print("HASIL EVALUASI METRIK MODEL:")
    print("=" * 40)
    
    # Metrik Random Forest
    r2_rf = r2_score(y_test, y_pred_rf)
    mae_rf = mean_absolute_error(y_test, y_pred_rf)
    rmse_rf = np.sqrt(mean_squared_error(y_test, y_pred_rf))
    print(f"Random Forest Regressor (Tuned Terbaik):")
    print(f"  - R² Score : {r2_rf:.4f} (~{r2_rf*100:.2f}%)")
    print(f"  - MAE      : {mae_rf:.4f}%")
    print(f"  - RMSE     : {rmse_rf:.4f}%")
    
    # Metrik Linear Regression
    r2_lr = r2_score(y_test, y_pred_lr)
    mae_lr = mean_absolute_error(y_test, y_pred_lr)
    rmse_lr = np.sqrt(mean_squared_error(y_test, y_pred_lr))
    print(f"Linear Regression (Baseline):")
    print(f"  - R² Score : {r2_lr:.4f} (~{r2_lr*100:.2f}%)")
    
    # Metrik Gradient Boosting
    r2_gb = r2_score(y_test, y_pred_gb)
    print(f"Gradient Boosting Regressor:")
    print(f"  - R² Score : {r2_gb:.4f} (~{r2_gb*100:.2f}%)")
    
    # 4. Ekspor Gambar Grafik ke Downloads
    print("\n[INFO] Mengekspor grafik visualisasi untuk laporan akademik...")
    downloads_dir = r"C:\Users\user\Downloads"
    if not os.path.exists(downloads_dir):
        downloads_dir = "."
        
    # Heatmap Korelasi
    plt.figure(figsize=(10, 8))
    sns.heatmap(df.corr(numeric_only=True), annot=True, cmap='coolwarm', fmt='.2f', linewidths=0.5)
    plt.title("Heatmap Korelasi Indikator Kemiskinan")
    plt.tight_layout()
    plt.savefig(os.path.join(downloads_dir, "2_Korelasi_Heatmap.png"), dpi=150)
    plt.close()
    
    # Feature Importance
    importance_df = pd.DataFrame({
        'Fitur': X.columns,
        'Importance': model_rf.feature_importances_
    }).sort_values(by='Importance', ascending=False)
    
    plt.figure(figsize=(10, 6))
    plt.barh(importance_df['Fitur'], importance_df['Importance'], color='#0d5c75')
    plt.gca().invert_yaxis()
    plt.title("Feature Importance - Faktor Penentu Kemiskinan")
    plt.tight_layout()
    plt.savefig(os.path.join(downloads_dir, "3_Feature_Importance.png"), dpi=150)
    plt.close()
    
    # Scatter Plot
    plt.figure(figsize=(10, 6))
    plt.scatter(y_test, y_pred_rf, color='#f59e0b', alpha=0.7)
    plt.plot([y.min(), y.max()], [y.min(), y.max()], 'r--', lw=2)
    plt.xlabel("Aktual")
    plt.ylabel("Prediksi")
    plt.title("Scatter Plot Hasil Prediksi Aktual vs Prediksi")
    plt.tight_layout()
    plt.savefig(os.path.join(downloads_dir, "4_Aktual_vs_Prediksi.png"), dpi=150)
    plt.close()
    
    print(f"[SUKSES] Semua grafik berhasil diekspor ke folder: {downloads_dir}")
    print("=" * 80)


